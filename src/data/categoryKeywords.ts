/** normalised keyword → category id, built once at module load. */
const LOOKUP: Map<string, string> = (() => {
  const map = new Map<string, string>();
  for (const [categoryId, words] of Object.entries(KEYWORDS)) {
    for (const word of words) {
      const key = normalizeTr(word);
      // First writer wins so a specific list never loses to a generic one.
      if (!map.has(key)) map.set(key, categoryId);
    }
  }
  return map;
})();

/** Total number of dictionary entries — asserted by the tests. */
export const KEYWORD_COUNT = LOOKUP.size;

/**
 * Guesses a category id for a product name.
 *
 * Tries the whole name first, then each word, then the longest keyword the
 * name contains. Falls back to "Diğer" when nothing matches.
 */
export function guessCategoryId(name: string): string {
  const normalized = normalizeTr(name);
  if (normalized.length === 0) return FALLBACK_CATEGORY_ID;

  const exact = LOOKUP.get(normalized);
  if (exact) return exact;

  const words = normalized.split(' ');
  // Prefer the last word: Turkish compounds put the head noun last
  // ("zeytin yağı" → yağ, "kedi maması" → mama).
  for (let i = words.length - 1; i >= 0; i--) {
    const hit = LOOKUP.get(words[i]!);
    if (hit) return hit;
  }

  // Finally, a substring match on the longest keyword that fits.
  let best: { id: string; length: number } | null = null;
  for (const [keyword, id] of LOOKUP) {
    if (keyword.length <= 3) continue; // too short to be meaningful
    if (normalized.includes(keyword) && (!best || keyword.length > best.length)) {
      best = { id, length: keyword.length };
    }
  }
  return best?.id ?? FALLBACK_CATEGORY_ID;
}
